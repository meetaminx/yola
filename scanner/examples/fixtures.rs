//! Prints deterministic testnet fixtures for Yola's TypeScript tests:
//! a viewing key pair from a fixed, publicly known test seed and the
//! addresses the scanner derives from it. The seed is test-only, appears in
//! this repository, and must never hold funds on any network.

use serde_json::json;
use yola_scanner::keys::{derive_address, fingerprint, parse_viewing_key};
use zcash_keys::keys::UnifiedSpendingKey;
use zcash_protocol::consensus::Network;
use zip32::AccountId;

fn main() {
    let net = Network::TestNetwork;
    let seed = [0x59u8; 32]; // "Y", repeated. Public test value.
    let usk = UnifiedSpendingKey::from_seed(&net, &seed, AccountId::ZERO).unwrap();
    let ufvk = usk.to_unified_full_viewing_key();
    let uivk = ufvk.to_unified_incoming_viewing_key().encode(&net).unwrap();
    let parsed = parse_viewing_key(&net, &uivk).unwrap();
    let base: u128 = 1 << 40;
    let mut addresses = vec![];
    let mut next = base;
    for _ in 0..6 {
        let (address, index) = derive_address(&net, &parsed.uivk, next).unwrap();
        addresses.push(json!({ "requested": next.to_string(), "index": index.to_string(), "address": address }));
        next = index + 1;
    }
    let main_uivk = UnifiedSpendingKey::from_seed(&Network::MainNetwork, &seed, AccountId::ZERO)
        .unwrap()
        .to_unified_full_viewing_key()
        .to_unified_incoming_viewing_key()
        .encode(&Network::MainNetwork)
        .unwrap();
    let (first_address, first_index) = derive_address(&net, &parsed.uivk, 0).unwrap();
    println!(
        "{}",
        serde_json::to_string_pretty(&json!({
            "note": "Generated by scanner/examples/fixtures.rs from a public test seed. Testnet only; never fund these.",
            "network": "test",
            "ufvk": ufvk.encode(&net).unwrap(),
            "uivk": uivk,
            "fingerprint": fingerprint(&uivk),
            "first_address": first_address,
            "first_index": first_index.to_string(),
            "mainnet_uivk": main_uivk,
            "addresses": addresses,
        }))
        .unwrap()
    );
}
